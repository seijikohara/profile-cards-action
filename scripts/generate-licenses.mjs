/**
 * @fileoverview Aggregate production-dependency license notices into dist/licenses.txt.
 *
 * tsdown inlines every production dependency into dist/index.js but has no built-in
 * license aggregation. This script rebuilds an equivalent notice by walking the pnpm
 * production dependency tree — the same modules tsdown bundles — and concatenating
 * each package's verbatim license text so the distributed bundle ships the notices
 * its dependencies require. It runs after the build.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const LICENSE_FILE_RE = /^licen[sc]e/i;
const outputPath = fileURLToPath(new URL('../dist/licenses.txt', import.meta.url));

/**
 * Return a package's verbatim license text, or an empty string when it ships none.
 */
function readLicenseText(packageDir) {
  if (!packageDir || !existsSync(packageDir)) {
    return '';
  }
  const licenseFile = readdirSync(packageDir).find((name) => LICENSE_FILE_RE.test(name));
  return licenseFile ? readFileSync(join(packageDir, licenseFile), 'utf8').trimEnd() : '';
}

// `pnpm licenses list` groups production dependencies by SPDX identifier and reports
// each package's resolved on-disk path, letting us recover the verbatim license.
const rawJson = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});

const packages = Object.values(JSON.parse(rawJson))
  .flat()
  .toSorted((left, right) => left.name.localeCompare(right.name));

const sections = packages.map((pkg) => {
  const version = (pkg.versions ?? []).join(', ');
  const homepage = pkg.homepage ? `\n${pkg.homepage}` : '';
  const licenseText = readLicenseText((pkg.paths ?? [])[0]);
  const body = licenseText ? `\n\n${licenseText}` : '';
  return `${'='.repeat(80)}\n${pkg.name}@${version} — ${pkg.license}${homepage}${body}\n`;
});

const header =
  'Third-party license notices for the production dependencies bundled into dist/index.js.\n' +
  'Generated by scripts/generate-licenses.mjs — do not edit by hand.\n\n';

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, header + sections.join('\n'));
// oxlint-disable-next-line no-console -- intentional CLI completion message for this build script
console.log(`Wrote ${outputPath} covering ${packages.length} production dependencies.`);
